namespace BasaraFoundry.Game.Utage.Art;

/// <summary>
/// In-memory StyleKitV0 using a 5x7 bitmap font. CI / smoke only.
/// Not a claim of Capcom-grade roulette lettering.
/// </summary>
public sealed class SyntheticStyleKitV0 : IStyleKitV0
{
    public (byte R, byte G, byte B) FillTop { get; init; } = (0xE8, 0xC8, 0x60);
    public (byte R, byte G, byte B) FillBottom { get; init; } = (0x8A, 0x5A, 0x10);
    public (byte R, byte G, byte B) Stroke { get; init; } = (0x10, 0x10, 0x18);
    public (byte R, byte G, byte B) BevelHi { get; init; } = (0xFF, 0xF0, 0xA0);
    public (byte R, byte G, byte B) BevelLo { get; init; } = (0x40, 0x28, 0x08);
    public int StrokeWidth { get; init; } = 1;

    public (int W, int H, byte[] Coverage) RasterizeGlyph(char c)
    {
        var rows = BitmapFont5x7.Get(c);
        const int w = BitmapFont5x7.Width;
        const int h = BitmapFont5x7.Height;
        var coverage = new byte[w * h];
        for (var y = 0; y < h; y++)
        {
            var row = rows[y];
            for (var x = 0; x < w; x++)
            {
                var bit = (row >> (w - 1 - x)) & 1;
                coverage[y * w + x] = (byte)(bit * 255);
            }
        }

        return (w, h, coverage);
    }

